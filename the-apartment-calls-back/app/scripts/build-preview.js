/*
 * Builds the free preview into dist/preview/ (or another folder under dist/).
 * The copy of story.js it writes holds only the opening call, so the paid calls,
 * contradictions and endings are not in the files you hand out.
 * The output folder must be new, empty, or an earlier preview build: nothing else is deleted.
 *
 *   node scripts/build-preview.js [outDir]
 */
"use strict";

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const outDir = path.resolve(process.argv[2] || path.join(root, "dist", "preview"));
const story = require("../js/story.js");

function isInside(child, parent) {
  const rel = path.relative(parent, child);
  return rel === "" || (!rel.startsWith("..") && !path.isAbsolute(rel));
}

// Check the path lexically, then reject symlinks inside dist/ so an output
// folder cannot redirect writes outside it. This also works where realpath
// access to the workspace's parent folders is restricted.
const distDir = path.join(root, "dist");
if (!isInside(outDir, distDir) || outDir === distDir) {
  throw new Error("Refusing to build into " + outDir + ": use a folder under dist/.");
}
let segmentPath = root;
for (const segment of path.relative(root, outDir).split(path.sep)) {
  segmentPath = path.join(segmentPath, segment);
  try {
    if (fs.lstatSync(segmentPath).isSymbolicLink()) {
      throw new Error("Refusing to build into " + outDir + ": symlink in output path.");
    }
  } catch (e) {
    if (e.code !== "ENOENT") throw e;
  }
}

// The only files a preview build contains. Anything else in outDir means it is not ours.
const OUTPUT_FILES = ["index.html", "css/style.css", "js/config.js", "js/story.js", "js/game.js", "js/ui.js"];
// First line of the generated js/story.js. Its presence is what marks a folder as an earlier preview build.
const BUILD_MARK = "/* Free preview: opening call only. Generated by scripts/build-preview.js — do not edit. */";

function listFiles(dir, prefix) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(function (entry) {
    const rel = prefix ? prefix + "/" + entry.name : entry.name;
    if (entry.isDirectory()) return listFiles(path.join(dir, entry.name), rel).concat(rel + "/");
    return [rel];
  });
}

if (fs.existsSync(outDir)) {
  if (!fs.statSync(outDir).isDirectory()) {
    throw new Error("Refusing to build into " + outDir + ": it is a file, not a folder.");
  }
  const foreign = listFiles(outDir, "").filter(function (rel) {
    return !OUTPUT_FILES.includes(rel) && rel !== "css/" && rel !== "js/";
  });
  if (foreign.length) {
    throw new Error("Refusing to build into " + outDir + ": it holds files that are not from a preview build ("
      + foreign.slice(0, 3).join(", ") + (foreign.length > 3 ? ", …" : "") + "). Use a new or empty folder.");
  }
  // Files with our names are only ours if the folder carries the build mark.
  const storyPath = path.join(outDir, "js", "story.js");
  const marked = fs.existsSync(storyPath) && fs.readFileSync(storyPath, "utf8").startsWith(BUILD_MARK);
  const ours = listFiles(outDir, "").filter(function (rel) { return OUTPUT_FILES.includes(rel); });
  if (ours.length && !marked) {
    throw new Error("Refusing to build into " + outDir + ": it holds " + ours.slice(0, 3).join(", ")
      + (ours.length > 3 ? ", …" : "") + " but is not an earlier preview build. Use a new or empty folder.");
  }
  // Remove only our own files, never the folder tree as a whole.
  OUTPUT_FILES.forEach(function (rel) { fs.rmSync(path.join(outDir, rel), { force: true }); });
}

function copy(rel) {
  fs.mkdirSync(path.dirname(path.join(outDir, rel)), { recursive: true });
  fs.copyFileSync(path.join(root, rel), path.join(outDir, rel));
}

function write(rel, text) {
  fs.mkdirSync(path.dirname(path.join(outDir, rel)), { recursive: true });
  fs.writeFileSync(path.join(outDir, rel), text);
}

["index.html", "css/style.css", "js/game.js", "js/ui.js"].forEach(copy);

const config = fs.readFileSync(path.join(root, "js/config.js"), "utf8");
const previewConfig = config.replace(/edition:\s*"full"/, 'edition: "preview"');
if (previewConfig === config) throw new Error('js/config.js: could not find edition: "full" to switch to preview');
write("js/config.js", previewConfig);

const freeStory = {
  opening: story.opening,
  calls: [],
  contradictions: [],
  decision: { heading: "", prompt: "", choices: [] },
  endings: []
};
write("js/story.js", [
  BUILD_MARK,
  "(function (root) {",
  '  "use strict";',
  "  const story = " + JSON.stringify(freeStory, null, 2).replace(/\n/g, "\n  ") + ";",
  '  if (typeof module === "object" && module.exports) {',
  "    module.exports = story;",
  "  } else {",
  "    root.ACB = root.ACB || {};",
  "    root.ACB.story = story;",
  "  }",
  '})(typeof window !== "undefined" ? window : globalThis);',
  ""
].join("\n"));

console.log("Preview built in " + outDir);
