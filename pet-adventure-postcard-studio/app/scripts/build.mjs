// Assemble the dependency-free browser entry point for direct file:// use.
// Keep the small source modules for focused tests and maintenance.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const files = [
  'config.js',
  'templates.js',
  'copy.js',
  'card-content.js',
  'layout.js',
  'render-card.js',
  'photo-file.js',
  'export-card.js',
  'main.js',
];
export function assembleBundle(root = process.cwd()) {
  const parts = files.map((file) => {
    const source = readFileSync(join(root, 'src', file), 'utf8');
    const code = source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
    if (/^(?:import|export)\b/m.test(code)) throw new Error(`Unbundled module syntax in ${file}`);
    return `  // src/${file}\n${code}`;
  });
  return `// Generated by npm run build. Open index.html directly to use the app.\n(() => {\n'use strict';\n${parts.join('\n')}\n})();\n`;
}

// npm invokes this file through stdin to avoid parent-directory resolution in
// restricted workspaces. Importing it from a test only assembles in memory.
if (process.argv.includes('--build-app')) {
  const root = process.cwd();
  writeFileSync(join(root, 'app.js'), assembleBundle(root));
}
